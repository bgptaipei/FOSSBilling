namespace Box\Mod\Product\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use FOSSBilling\Doctrine\TimestampTrait;
use FOSSBilling\Interfaces\TimestampInterface;

#[ORM\Entity(repositoryClass: \Box\Mod\Product\Repository\ProductOptionGroupRepository::class)]
#[ORM\Table(name: 'product_option_group')]
#[ORM\UniqueConstraint(name: 'product_option_group_product_code', columns: ['product_id', 'code'])]
#[ORM\HasLifecycleCallbacks]
class ProductOptionGroup implements TimestampInterface
{
    use TimestampTrait;

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(name: 'product_id', type: Types::BIGINT)]
    private int $productId = 0;

    #[ORM\Column(type: Types::STRING, length: 64)]
    private string $code = '';

    #[ORM\Column(type: Types::STRING, length: 255)]
    private string $label = '';

    #[ORM\Column(type: Types::BOOLEAN, options: ['default' => true])]
    private bool $required = true;

    #[ORM\Column(name: 'min_count', type: Types::INTEGER, options: ['default' => 1])]
    private int $minCount = 1;

    #[ORM\Column(name: 'max_count', type: Types::INTEGER, options: ['default' => 1])]
    private int $maxCount = 1;

    #[ORM\Column(type: Types::STRING, length: 3, options: ['default' => 'USD'])]
    private string $currency = 'USD';

    #[ORM\Column(type: Types::STRING, length: 64, options: ['default' => '1M'])]
    private string $periods = '1M';

    #[ORM\Column(type: Types::BOOLEAN, options: ['default' => false])]
    private bool $verified = false;

    #[ORM\Column(type: Types::BOOLEAN, options: ['default' => true])]
    private bool $active = true;

    #[ORM\Column(name: 'sort_order', type: Types::INTEGER, options: ['default' => 0])]
    private int $sortOrder = 0;

    public function getId(): ?int
    {
        return $this->id === null ? null : (int) $this->id;
    }

    public function getProductId(): int
    {
        return (int) $this->productId;
    }

    public function setProductId(int $productId): self
    {
        $this->productId = $productId;

        return $this;
    }

    public function getCode(): string
    {
        return $this->code;
    }

    public function setCode(string $code): self
    {
        $this->code = $code;

        return $this;
    }

    public function getLabel(): string
    {
        return $this->label;
    }

    public function setLabel(string $label): self
    {
        $this->label = $label;

        return $this;
    }

    public function isRequired(): bool
    {
        return $this->required;
    }

    public function setRequired(bool $required): self
    {
        $this->required = $required;

        return $this;
    }

    public function getMinCount(): int
    {
        return $this->minCount;
    }

    public function setMinCount(int $minCount): self
    {
        $this->minCount = $minCount;

        return $this;
    }

    public function getMaxCount(): int
    {
        return $this->maxCount;
    }

    public function setMaxCount(int $maxCount): self
    {
        $this->maxCount = $maxCount;

        return $this;
    }

    public function getCurrency(): string
    {
        return $this->currency;
    }

    public function setCurrency(string $currency): self
    {
        $this->currency = $currency;

        return $this;
    }

    public function getPeriods(): string
    {
        return $this->periods;
    }

    public function setPeriods(string $periods): self
    {
        $this->periods = $periods;

        return $this;
    }

    public function isVerified(): bool
    {
        return $this->verified;
    }

    public function setVerified(bool $verified): self
    {
        $this->verified = $verified;

        return $this;
    }

    public function isActive(): bool
    {
        return $this->active;
    }

    public function setActive(bool $active): self
    {
        $this->active = $active;

        return $this;
    }

    public function getSortOrder(): int
    {
        return $this->sortOrder;
    }

    public function setSortOrder(int $sortOrder): self
    {
        $this->sortOrder = $sortOrder;

        return $this;
    }
}
