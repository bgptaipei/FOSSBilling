namespace Box\Mod\Product\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use FOSSBilling\Doctrine\TimestampTrait;
use FOSSBilling\Interfaces\TimestampInterface;

#[ORM\Entity(repositoryClass: \Box\Mod\Product\Repository\ProductOptionValueRepository::class)]
#[ORM\Table(name: 'product_option_value')]
#[ORM\UniqueConstraint(name: 'product_option_value_group_code', columns: ['group_id', 'code'])]
#[ORM\HasLifecycleCallbacks]
class ProductOptionValue implements TimestampInterface
{
    use TimestampTrait;

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(name: 'group_id', type: Types::BIGINT)]
    private int $groupId = 0;

    #[ORM\Column(type: Types::STRING, length: 64)]
    private string $code = '';

    #[ORM\Column(type: Types::STRING, length: 255)]
    private string $label = '';

    #[ORM\Column(name: 'monthly_price_cents', type: Types::INTEGER, options: ['default' => 0])]
    private int $monthlyPriceCents = 0;

    #[ORM\Column(name: 'setup_price_cents', type: Types::INTEGER, options: ['default' => 0])]
    private int $setupPriceCents = 0;

    #[ORM\Column(name: 'is_default', type: Types::BOOLEAN, options: ['default' => false])]
    private bool $isDefault = false;

    #[ORM\Column(type: Types::BOOLEAN, options: ['default' => true])]
    private bool $active = true;

    #[ORM\Column(name: 'stock_control', type: Types::BOOLEAN, options: ['default' => false])]
    private bool $stockControl = false;

    #[ORM\Column(name: 'quantity_in_stock', type: Types::INTEGER, options: ['default' => 0])]
    private int $quantityInStock = 0;

    #[ORM\Column(name: 'sort_order', type: Types::INTEGER, options: ['default' => 0])]
    private int $sortOrder = 0;

    public function getId(): ?int
    {
        return $this->id === null ? null : (int) $this->id;
    }

    public function getGroupId(): int
    {
        return (int) $this->groupId;
    }

    public function setGroupId(int $groupId): self
    {
        $this->groupId = $groupId;

        return $this;
    }

    public function getCode(): string
    {
        return $this->code;
    }

    public function setCode(string $code): self
    {
        $this->code = $code;

        return $this;
    }

    public function getLabel(): string
    {
        return $this->label;
    }

    public function setLabel(string $label): self
    {
        $this->label = $label;

        return $this;
    }

    public function getMonthlyPriceCents(): int
    {
        return $this->monthlyPriceCents;
    }

    public function setMonthlyPriceCents(int $monthlyPriceCents): self
    {
        $this->monthlyPriceCents = $monthlyPriceCents;

        return $this;
    }

    public function getSetupPriceCents(): int
    {
        return $this->setupPriceCents;
    }

    public function setSetupPriceCents(int $setupPriceCents): self
    {
        $this->setupPriceCents = $setupPriceCents;

        return $this;
    }

    public function isDefault(): bool
    {
        return $this->isDefault;
    }

    public function setIsDefault(bool $isDefault): self
    {
        $this->isDefault = $isDefault;

        return $this;
    }

    public function isActive(): bool
    {
        return $this->active;
    }

    public function setActive(bool $active): self
    {
        $this->active = $active;

        return $this;
    }

    public function isStockControl(): bool
    {
        return $this->stockControl;
    }

    public function setStockControl(bool $stockControl): self
    {
        $this->stockControl = $stockControl;

        return $this;
    }

    public function getQuantityInStock(): int
    {
        return $this->quantityInStock;
    }

    public function setQuantityInStock(int $quantityInStock): self
    {
        $this->quantityInStock = $quantityInStock;

        return $this;
    }

    public function getSortOrder(): int
    {
        return $this->sortOrder;
    }

    public function setSortOrder(int $sortOrder): self
    {
        $this->sortOrder = $sortOrder;

        return $this;
    }
}
